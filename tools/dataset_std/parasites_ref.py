"""Standardizer for the three intestinal-parasites reference datasets (eggs / larvae / cysts)."""

import tarfile
from pathlib import Path

from .base import DatasetStandardizer, RawItem, register

# Filename prefix -> species, transcribed from the tables in the source README.
# Base renumbers classes alphabetically, so this table plus the prefix kept in the
# covariates is what makes the original class ids recoverable.
CLASS_NAMES = {
    "helminth-eggs": {
        "000001": "Hymenolepis nana",
        "000002": "Hymenolepis diminuta",
        "000003": "Ancylostoma",
        "000004": "Enterobius vermicularis",
        "000005": "Ascaris lumbricoides",
        "000006": "Trichuris trichiura",
        "000007": "Schistosoma mansoni",
        "000008": "Taenia spp",
        "000009": "Impurities",
    },
    "helminth-larvae": {
        "000001": "Strongyloides stercoralis",
        "000002": "Impurities",
    },
    "protozoan-cysts": {
        "000001": "Entamoeba coli",
        "000002": "Entamoeba histolytica",
        "000003": "Endolimax nana",
        "000004": "Giardia intestinalis",
        "000005": "Iodamoeba butschlii",
        "000006": "Blastocystis hominis",
        "000007": "Impurities",
    },
}


@register
class ParasitesRef(DatasetStandardizer):
    name = "parasites_ref"

    def discover(self):
        subset = self.cfg["subset"]
        names = CLASS_NAMES[subset]
        src = Path(self.cfg["root"]) / subset
        scratch = Path(self.cfg["out"]) / "_extract"

        for archive in ("images", "masks"):
            dest = scratch / archive
            if not dest.exists():
                with tarfile.open(src / f"{archive}.tar.bz2", "r:bz2") as tar:
                    tar.extractall(dest, filter="data")

        # images.tar.bz2 nests everything under an "images/" folder; masks.tar.bz2 does not
        for img in sorted((scratch / "images" / "images").iterdir()):
            mask = scratch / "masks" / img.name
            prefix = img.name.split("_")[0]
            yield RawItem(
                image=img,
                label=names[prefix],
                mask=mask if mask.exists() else None,
                covariates={"orig_class_prefix": prefix},
            )
