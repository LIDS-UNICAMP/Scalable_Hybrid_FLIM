"""Standardizer for the coconut-trees dataset (coco / non_coco tiles)."""

from pathlib import Path

from .base import DatasetStandardizer, RawItem, register

EXTS = {".png", ".jpg", ".jpeg"}


@register
class CoconutTrees(DatasetStandardizer):
    name = "coconut_trees"

    def discover(self):
        root = Path(self.cfg["root"])
        for label in ("coco", "non_coco"):
            for img in sorted((root / label).iterdir()):
                if img.suffix.lower() not in EXTS:
                    continue
                # filenames are "<tile>-<label>-<n>.png"
                tile = img.name.split("-", 1)[0]
                yield RawItem(
                    image=img,
                    label=label,
                    covariates={"tile": tile if tile in ("lower", "upper") else "other"},
                )
