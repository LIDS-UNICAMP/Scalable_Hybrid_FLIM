"""Standardizer for the AID scene-classification dataset (30 classes, flat folders)."""

from pathlib import Path

from .base import DatasetStandardizer, RawItem, register

EXTS = {".jpg", ".jpeg", ".png"}


@register
class AID(DatasetStandardizer):
    name = "aid"

    def discover(self):
        root = Path(self.cfg["root"]) / "AID"
        for class_dir in sorted(p for p in root.iterdir() if p.is_dir()):
            for img in sorted(class_dir.iterdir()):
                if img.is_file() and img.suffix.lower() in EXTS:
                    yield RawItem(image=img, label=class_dir.name)
