"""Standardizer for Food-101 (101 classes, nested tree, split recorded as a covariate)."""

from pathlib import Path

from .base import DatasetStandardizer, RawItem, register

EXTS = {".jpg", ".jpeg", ".png"}


def _images_dir(root: Path) -> Path:
    # the archive unpacks an extra "food-101" level, so accept either depth
    for cand in (root / "food-101" / "food-101" / "images", root / "food-101" / "images", root / "images"):
        if cand.is_dir():
            return cand
    raise FileNotFoundError(f"no food-101 images/ under {root}")


def _split_of_stem(meta: Path) -> dict:
    lookup = {}
    for split in ("train", "test"):
        # lines look like "apple_pie/1005649"; stems are unique across the whole dataset
        for line in (meta / f"{split}.txt").read_text().split():
            lookup[line.rsplit("/", 1)[-1]] = split
    return lookup


@register
class Food101(DatasetStandardizer):
    name = "food101"

    def discover(self):
        images = _images_dir(Path(self.cfg["root"]))
        split_of = _split_of_stem(images.parent / "meta")
        for class_dir in sorted(p for p in images.iterdir() if p.is_dir()):
            for img in sorted(class_dir.iterdir()):
                if img.is_file() and img.suffix.lower() in EXTS:
                    yield RawItem(
                        image=img,
                        label=class_dir.name,
                        covariates={"orig_split": split_of.get(img.stem, "unknown")},
                    )
