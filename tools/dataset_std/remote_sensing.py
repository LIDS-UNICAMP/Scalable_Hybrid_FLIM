"""Standardizer for the remote-sensing YOLO detection set (image label = mode of its boxes)."""

import re
from collections import Counter
from pathlib import Path

import yaml

from .base import DatasetStandardizer, RawItem, register

EXTS = {".jpg", ".jpeg", ".png"}
# used only if data.yaml cannot be parsed
NAMES = ["Agriculture", "Airport", "Beach", "City", "Desert", "Forest", "Grassland",
         "Highway", "Lake", "Mountain", "Parking", "Port", "Railway", "River"]
# "002_jpg.rf.<hash>" -> "002": all rf copies of one source image share the group
GROUP_RE = re.compile(r"^(.+?)_[A-Za-z0-9]+\.rf\.")


@register
class RemoteSensing(DatasetStandardizer):
    name = "remote_sensing"

    def discover(self):
        root = Path(self.cfg["root"]) / "Remote Sensing Data.v2i.yolov8"
        try:
            names = yaml.safe_load((root / "data.yaml").read_text())["names"]
        except Exception:
            names = NAMES
        self.skipped = 0
        for split in ("train", "valid", "test"):
            for img in sorted((root / split / "images").iterdir()):
                if img.suffix.lower() not in EXTS:
                    continue
                txt = root / split / "labels" / (img.stem + ".txt")
                lines = txt.read_text().splitlines() if txt.exists() else []
                idxs = [int(ln.split()[0]) for ln in lines if ln.strip()]  # "<cls> cx cy ..."
                if not idxs:
                    self.skipped += 1  # no boxes -> no label to stratify on
                    continue
                counts = Counter(idxs)
                idx = min(counts, key=lambda i: (-counts[i], i))  # mode, ties by lowest index
                m = GROUP_RE.match(img.stem)
                yield RawItem(
                    image=img,
                    label=names[idx],
                    group=m.group(1) if m else img.stem,
                    covariates={"orig_split": split, "n_boxes": len(idxs)},
                )
