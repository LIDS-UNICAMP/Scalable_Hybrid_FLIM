"""fer2013.py — discover() do FER-2013 para o padronizador de datasets.

Layout de origem: <split>/<Emotion>/<n>.png, com split em train/val/test e
Emotion em Angry, Disgust, Fear, Happy, Neutral, Sad, Surprise.

Sem grupo de leakage (o FER-2013 nao traz identidade de sujeito em disco) e sem
mascara. O split original vira covariavel: o re-split e feito do zero, mas a
pertinencia original fica auditavel.
"""

from pathlib import Path

from .base import DatasetStandardizer, RawItem, register

SPLITS = ("train", "val", "test")
EXTS = {".png", ".jpg", ".jpeg"}


@register
class FER2013(DatasetStandardizer):
    name = "fer2013"

    def discover(self):
        root = Path(self.cfg["root"]).expanduser().resolve()
        for split in SPLITS:
            for emotion_dir in sorted((root / split).iterdir()):
                if not emotion_dir.is_dir():
                    continue
                for img in sorted(emotion_dir.iterdir()):
                    if img.suffix.lower() not in EXTS:
                        continue
                    yield RawItem(
                        image=img,  # absoluto: root ja veio resolvido
                        label=emotion_dir.name,
                        covariates={"orig_split": split},
                    )
