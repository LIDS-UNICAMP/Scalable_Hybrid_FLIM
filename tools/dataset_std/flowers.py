"""Standardizer for the flowers dataset (5 flower species)."""

from pathlib import Path

from .base import DatasetStandardizer, RawItem, register

EXTS = {".png", ".jpg", ".jpeg"}


@register
class Flowers(DatasetStandardizer):
    name = "flowers"

    def discover(self):
        # only train/ is labeled; test/ is a flat Kaggle submission set with no
        # ground truth (Testing_set_flower.csv carries filenames only), so it is skipped
        train = Path(self.cfg["root"]) / "train"
        for class_dir in sorted(p for p in train.iterdir() if p.is_dir()):
            for img in sorted(class_dir.iterdir()):
                if img.suffix.lower() not in EXTS:
                    continue
                yield RawItem(
                    image=img,
                    label=class_dir.name,
                    covariates={"orig_split": "train"},
                )
