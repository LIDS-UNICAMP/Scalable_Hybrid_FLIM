"""Estado duravel do launcher Ray (resume).

Movido verbatim de ``scripts/run_ssl_ray.py:316-344``. Nada aqui foi
redesenhado: mesmas chaves no JSON, mesmo corpo, so o import mudou.

O ``_log`` veio junto de ``scripts/run_ssl_ray.py:305-313`` porque a classe
depende dele e nao ha modulo de log compartilhado no pacote; as constantes
saem de ``experiments/constants.py``.
"""
from __future__ import annotations

import json
import os
import time

from experiments.constants import (
    LOG_LEVEL_DEFAULT,
    LOG_LEVELS as _LOG_LEVELS,
    LOG_TIME_FMT,
)

_current_log_level = _LOG_LEVELS[LOG_LEVEL_DEFAULT]


def _log(msg: str, level: str = "INFO") -> None:
    if _LOG_LEVELS.get(level, 1) >= _current_log_level:
        ts = time.strftime(LOG_TIME_FMT)
        print(f"[{ts}][{level}] {msg}", flush=True)


class ExecutionState:
    """Persists per-experiment outcomes so a re-run can skip completed ones."""

    def __init__(self, state_file: str) -> None:
        self.state_file = state_file
        self._state: dict[str, dict] = {}
        self._load()

    def _load(self) -> None:
        if os.path.exists(self.state_file):
            with open(self.state_file) as f:
                self._state = json.load(f)
            _log(f"Resume state loaded ({len(self._state)} record(s))")

    def is_completed(self, key: str) -> bool:
        return self._state.get(key, {}).get("status") == "ok"

    def mark(self, key: str, result: dict) -> None:
        self._state[key] = {
            "status":     result.get("status", "unknown"),
            "timestamp":  time.time(),
            "returncode": result.get("returncode"),
        }
        os.makedirs(os.path.dirname(os.path.abspath(self.state_file)), exist_ok=True)
        with open(self.state_file, "w") as f:
            json.dump(self._state, f, indent=2)

    def completed_keys(self) -> list[str]:
        return [k for k, v in self._state.items() if v.get("status") == "ok"]
