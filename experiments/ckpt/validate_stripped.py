"""Valida que o student carregado de um .ckpt original e do seu .student.ckpt é IDÊNTICO.
Usa o MESMO loader do avaliador (_load_student_from_ckpt) — prova que o eval não muda.

  python -m experiments.ckpt.validate_stripped <original.ckpt> <stripped.student.ckpt>

Rodado com ``-m`` da raiz do repositorio, ``sys.path[0]`` e a raiz e o
``from eval.svm_variants...`` abaixo resolve. Como ``scripts/validate_stripped_ckpt.py``
ele morria com ModuleNotFoundError (era o bug de scripts/README.md:165); o move
para o pacote conserta isso sem uma linha de sys.path.
"""
import sys, torch
from eval.svm_variants.svm_distillation_conv import _load_student_from_ckpt

def validate_stripped(original: str, stripped: str) -> int:
    dev = torch.device("cpu")
    sa = _load_student_from_ckpt(original, dev).state_dict()
    sb = _load_student_from_ckpt(stripped, dev).state_dict()
    assert sa.keys() == sb.keys(), f"chaves diferentes: {set(sa)^set(sb)}"
    npar = sum(v.numel() for v in sa.values())
    maxdiff = 0.0
    for k in sa:
        assert sa[k].shape == sb[k].shape, f"shape difere em {k}"
        d = (sa[k].float() - sb[k].float()).abs().max().item()
        maxdiff = max(maxdiff, d)
    print(f"OK  | {len(sa)} tensores | {npar/1e3:.0f}k params | "
          f"maior diferença absoluta = {maxdiff:.2e}  -> {'IDÊNTICO' if maxdiff==0 else 'DIVERGE!'}")
    return 0 if maxdiff == 0 else 1

if __name__ == "__main__":
    raise SystemExit(validate_stripped(sys.argv[1], sys.argv[2]))
