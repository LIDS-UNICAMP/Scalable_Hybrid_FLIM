"""CustomLightningCLI: o LightningCLI do train.py, que fala YAML."""

from __future__ import annotations

from lightning.pytorch.cli import LightningCLI


class CustomLightningCLI(LightningCLI):
    """Lightning CLI para o treino auto-supervisionado FLIM."""

    def __init__(self, *args, **kwargs) -> None:
        kwargs.setdefault("save_config_kwargs", {"overwrite": True})
        super().__init__(*args, **kwargs)

    def add_arguments_to_parser(self, parser) -> None:
        super().add_arguments_to_parser(parser)
        parser.link_arguments("trainer.max_epochs", "model.init_args.max_epochs")

        # Flag de topo, configuravel por YAML e por linha de comando.
        parser.add_argument("--use_wandb", type=bool, default=True)

    def before_instantiate_classes(self) -> None:
        """Ajusta a config antes de instanciar Trainer/Model/Data.

        Le a flag de topo `use_wandb`: quando ela e falsa, troca o WandbLogger
        configurado por um CSVLogger leve.
        """
        super().before_instantiate_classes()

        # Com parser_mode="omegaconf", `self.config` e um objeto OmegaConf.
        use_wandb = bool(getattr(self.config, "use_wandb", True))
        if use_wandb:
            return

        # Troca a config de trainer.logger.
        # O CSVLogger esta sempre disponivel (nao depende de servico externo).
        if hasattr(self.config, "trainer"):
            self.config.trainer.logger = {
                "class_path": "lightning.pytorch.loggers.CSVLogger",
                "init_args": {
                    "save_dir": "logs",
                    "name": "csv",
                },
            }
