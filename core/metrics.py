"""Metrica unica de classificacao do projeto.

Regra permanente: existe UMA `compute_metrics` e ela vive aqui. Nenhum avaliador,
modulo Lightning, sonda de validacao ou script de analise recalcula kappa, acc ou
f1 por conta propria.

Convencoes canonicas (nao sao negociaveis por argumento):

* rotulo 0-indexado, em [0, num_classes). Quem treina SVM com rotulo 1-indexado
  subtrai 1 antes de chamar aqui.
* averaging macro em tudo. "acc" e acuracia BALANCEADA (media por classe), nao a
  fracao de acertos; e o default do torchmetrics e o repo inteiro ja reporta
  assim.
"""

from __future__ import annotations

import numpy as np
import torch
from torch import Tensor
from torchmetrics.functional.classification import (
    multiclass_accuracy,
    multiclass_cohen_kappa,
    multiclass_f1_score,
)


def compute_metrics(
    y_true: Tensor | np.ndarray,
    y_pred: Tensor | np.ndarray,
    num_classes: int,
) -> dict[str, float]:
    """Calcula kappa, acuracia balanceada e f1-macro de uma avaliacao.

    Args:
        y_true: rotulos verdadeiros 0-indexados, shape (N,).
        y_pred: classes preditas (N,) ou logits/probabilidades (N, C) — o argmax
            e feito aqui.
        num_classes: numero total de classes.

    Returns:
        Dict com as chaves 'kappa', 'acc' e 'f1'.
    """
    if isinstance(y_true, np.ndarray):
        y_true = torch.from_numpy(y_true)
    if isinstance(y_pred, np.ndarray):
        y_pred = torch.from_numpy(y_pred)

    y_true = y_true.long()
    if y_pred.ndim == 2:
        y_pred = y_pred.argmax(dim=1)
    y_pred = y_pred.long()

    return {
        "kappa": float(multiclass_cohen_kappa(y_pred, y_true, num_classes=num_classes)),
        "acc": float(multiclass_accuracy(y_pred, y_true, num_classes=num_classes)),
        "f1": float(multiclass_f1_score(y_pred, y_true, num_classes=num_classes, average="macro")),
    }
