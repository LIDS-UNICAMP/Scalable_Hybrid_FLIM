"""
Variante sigmoid do modelo de classificacao: encoder pronto + cabeca de duas
camadas (Sigmoid, Sigmoid+ReLU ou Softplus).

Movido de src/models/models.py:438 (SigmoidClassificationModel). Nao herda de
ClassificationModel: o __init__ diverge pela validacao de flags mutuamente
exclusivas e pela escolha de 3 vias da cabeca. Mesma mudanca de assinatura de
C20 — o encoder chega pronto e in_features vem por argumento.
"""

from typing import Optional

import torch
import torch.nn as nn

from core.blocks.two_layer_sigmoid_head import TwoLayerSigmoidHead
from core.blocks.two_layer_softplus_head import TwoLayerSoftplusHead


class SigmoidClassificationModel(nn.Module):
    """
    FLIM Encoder + two-layer Sigmoid classification head.

    The output activation of the head is selected by two mutually exclusive
    flags: ``output_relu=True`` uses ``TwoLayerSigmoidHead`` with a ReLU before
    the Softmax, ``output_softplus=True`` swaps the head for
    ``TwoLayerSoftplusHead``, and with both ``False`` the plain
    ``TwoLayerSigmoidHead`` is used. Either way the attribute is ``self.head``
    and the ``state_dict`` keys are the same across all three variants.
    """

    def __init__(self, encoder: nn.Module, in_features: int, num_classes: int,
                 hidden_dim: Optional[int] = None, output_relu: bool = False,
                 output_softplus: bool = False):
        super().__init__()
        if output_relu and output_softplus:
            raise ValueError(
                "output_relu and output_softplus are mutually exclusive: "
                "pick at most one output activation for the classification head."
            )
        self.encoder = encoder
        if output_softplus:
            self.head = TwoLayerSoftplusHead(in_features, num_classes, hidden_dim)
        else:
            self.head = TwoLayerSigmoidHead(in_features, num_classes, hidden_dim,
                                            output_relu=output_relu)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        features = self.encoder(x)
        return self.head(features)
