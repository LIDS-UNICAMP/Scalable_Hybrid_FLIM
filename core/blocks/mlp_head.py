"""
Cabeca MLP generica de classificacao.

Movida de src/models/models.py:304 (MLPHead) sem nenhuma alteracao de corpo:
mesma ordem de camadas, mesmos defaults, mesma inicializacao implicita do torch.
"""

import torch
import torch.nn as nn


class MLPHead(nn.Module):
    """
    MLP classification head with adaptive average pooling to handle variable
    spatial dimensions from the encoder output.
    """

    def __init__(self, in_features: int, num_classes: int, hidden_dim: int = 256, dropout: float = 0.3):
        super().__init__()
        self.pool = nn.AdaptiveAvgPool2d(1)
        self.classifier = nn.Sequential(
            nn.Linear(in_features, hidden_dim),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim, hidden_dim // 2),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(hidden_dim // 2, num_classes),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.pool(x)
        x = x.view(x.size(0), -1)
        return self.classifier(x)
