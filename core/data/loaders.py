"""Leitores de imagem: um PIL/RGB e um IFT/LAB. Quem escolhe o loader e o dataset."""

from PIL import Image

import pyift.pyift as ift


def pil_loader(image_path):
    with open(image_path, "rb") as f:
        img = Image.open(f)
        return img.convert("RGB")


_MAGIC_EXT = ((b"\x89PNG", ".png"), (b"\xff\xd8", ".jpg"))


def _ext_consistent_path(image_path):
    """pyift picks the decoder from the file EXTENSION. Some datasets ship PNG bytes under a
    ``.jpg`` name (aid: 468 files). For those, return a symlink with the right extension in a
    per-user cache dir (the dataset file itself is never touched); otherwise the path itself."""
    import os
    import hashlib
    path = str(image_path)
    ext = os.path.splitext(path)[1].lower()
    try:
        with open(path, "rb") as f:
            head = f.read(4)
    except OSError:
        return path
    real = next((e for magic, e in _MAGIC_EXT if head.startswith(magic)), None)
    if real is None or (real == ".jpg" and ext in (".jpg", ".jpeg")) or real == ext:
        return path
    cache = os.path.join(os.path.expanduser("~"), ".cache", "ift_ext_fix")
    os.makedirs(cache, exist_ok=True)
    link = os.path.join(cache, hashlib.sha1(os.path.abspath(path).encode()).hexdigest() + real)
    if not os.path.lexists(link):
        try:
            os.symlink(os.path.abspath(path), link)
        except FileExistsError:
            pass
    return link


def ift_lab_loader(image_path):
    """Load image as LABNorm2 using pyift (same as FLIM training pipeline).
    Returns a PIL-compatible numpy array with 3 channels in [0, 1] range."""
    image = ift.ReadImageByExt(_ext_consistent_path(image_path))
    mimage = ift.ImageToMImage(image, color_space=ift.LABNorm2_CSPACE)
    lab_image = mimage.AsNumPy().squeeze()  # (H, W, 3), float in [0, 1]
    return lab_image
