"""spifil_residual.py — camadas com concatenação estilo DenseNet (§7): C_l = C_(l-1) + N_l."""

import torch

from ga_search.spifil_ext import ActivationBlock, build_learner


class ResidualBlock(ActivationBlock):
    """pool(cat([x, act(conv(x))])): a entrada inteira segue junto com os N_l filtros novos."""

    @property
    def out_channels(self):
        return self.in_channels + int(self.conv.out_channels)

    def forward(self, x):
        x = torch.cat([x, self.act(self.conv(x))], dim=1)
        return x if self.pool is None else self.pool(x)


def build_residual_learner(cfg, samples, *, device, leaky_slope):
    """build_learner com ResidualBlock nas camadas l>=2; a camada 1 é ActivationBlock (C_1 = N_1).

    O SpifilNet monta o bloco l+1 com in_channels = N_l; aqui ele é refeito com o C_l planejado.
    Se o allocator entregar menos filtros, o rewire do SpifilNet.set_filters refaz o bloco
    seguinte com o out_channels real (= C), usando o mesmo block_factory.
    """
    learn = build_learner(cfg, samples, device=device, leaky_slope=leaky_slope,
                          block_factory=ResidualBlock)
    specs, blocks = learn.arch.layers, learn.model.blocks
    blocks[0] = ActivationBlock(specs[0], learn.color.out_channels).to(learn.device)
    for l in range(1, len(specs)):
        blocks[l] = ResidualBlock(specs[l], cfg["layers"][l - 1]["channels"]).to(learn.device)
    return learn
