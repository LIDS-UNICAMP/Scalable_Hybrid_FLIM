"""Valida que o student carregado de um .ckpt original e do seu .student.ckpt é IDÊNTICO.
Usa o MESMO loader do avaliador (_load_student_from_ckpt) — prova que o eval não muda.

  python scripts/validate_stripped_ckpt.py <original.ckpt> <stripped.student.ckpt>
"""
import sys, torch
from src.evaluate.svm_distillation_conv import _load_student_from_ckpt

def main(a, b):
    dev = torch.device("cpu")
    sa = _load_student_from_ckpt(a, dev).state_dict()
    sb = _load_student_from_ckpt(b, dev).state_dict()
    assert sa.keys() == sb.keys(), f"chaves diferentes: {set(sa)^set(sb)}"
    npar = sum(v.numel() for v in sa.values())
    maxdiff = 0.0
    for k in sa:
        assert sa[k].shape == sb[k].shape, f"shape difere em {k}"
        d = (sa[k].float() - sb[k].float()).abs().max().item()
        maxdiff = max(maxdiff, d)
    print(f"OK  | {len(sa)} tensores | {npar/1e3:.0f}k params | "
          f"maior diferença absoluta = {maxdiff:.2e}  -> {'IDÊNTICO' if maxdiff==0 else 'DIVERGE!'}")
    return 0 if maxdiff == 0 else 1

if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
