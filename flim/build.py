"""
Porta unica do pacote ``flim``.

``build`` monta o Encoder FLIM a partir do ``architecture.json`` e, quando o eixo
``init`` vale ``flim``, carrega os pesos FLIM dentro dele. Nao define arquitetura,
nao le json e nao abre arquivo de peso por conta propria: quem interpreta o arch e
``flim.arch``, quem le e transforma tensor e ``flim.weights``.

Os outros valores do eixo ``init`` (``he``, ``xavier``, ``trunc_normal``,
``random``) NAO sao resolvidos aqui — o encoder volta com o init default do torch e
quem aplica a funcao de init e ``core/blocks/init.py``.
"""
from __future__ import annotations

from typing import Optional

from flim.encoder import Encoder


def build(
    arch_json: str,
    init: str,
    weights_path: Optional[str] = None,
    in_channels: int = 3,
) -> Encoder:
    """Devolve o Encoder descrito por ``arch_json``, pronto para uso.

    Args:
        arch_json:    Caminho do ``architecture.json`` do FLIM.
        init:         Valor do eixo de init. So ``"flim"`` e resolvido aqui.
        weights_path: Diretorio com ``conv{n}-kernels.npy`` / ``conv{n}-bias.txt``.
                      Obrigatorio quando ``init="flim"``, ignorado nos demais.
        in_channels:  Canais da imagem de entrada.
    """
    if init == "flim" and not weights_path:
        raise ValueError("weights_path e obrigatorio quando init='flim'")

    return Encoder.from_flim(arch_json, in_channels, weights_path if init == "flim" else None)
