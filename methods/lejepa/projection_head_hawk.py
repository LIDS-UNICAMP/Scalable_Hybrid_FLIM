"""
Head de projecao do LeJEPA, variante Hawk.

Movida de src/models/lejepa.py:28 (ProjectionHeadHawk) sem nenhuma alteracao de
corpo: mesma ordem de camadas, mesmas dimensoes, mesmas chaves de state_dict.
Fica em arquivo separado de ProjectionHead de proposito: sao duas classes
distintas escolhidas pelo class_path do YAML, nao uma so.
"""

import torch
import torch.nn as nn


class ProjectionHeadHawk(nn.Module):
    """3-layer MLP projection head with BatchNorm (matches LeJEPA reference)."""

    def __init__(self, in_dim: int, hidden_dim: int, out_dim: int) -> None:
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(in_dim, hidden_dim, bias=False),
            nn.BatchNorm1d(hidden_dim),
            nn.ReLU(inplace=True),
            nn.Linear(hidden_dim, hidden_dim, bias=False),
            nn.BatchNorm1d(hidden_dim),
            nn.ReLU(inplace=True),
            nn.Linear(hidden_dim, out_dim, bias=False),
            nn.BatchNorm1d(out_dim),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x)
