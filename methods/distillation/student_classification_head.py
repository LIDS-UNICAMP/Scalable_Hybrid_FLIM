"""
Cabeca linear de classificacao do aluno.

Movida de src/models/distillation.py:797 (StudentClassificationHead) sem nenhuma
alteracao de corpo: mesma camada, mesmo nome de atributo `head` e mesmas chaves
de state_dict.

NAO foi substituida por core.blocks.MLPHead: as duas classes nao sao
equivalentes. MLPHead tem AdaptiveAvgPool2d + Sequential de 3 Linear com chaves
`classifier.{0,3,6}.*`; esta aqui e um unico nn.Linear com chaves `head.*`.
Trocar renomearia as chaves e quebraria todo checkpoint ja gravado.
"""
from __future__ import annotations

import torch.nn as nn
from torch import Tensor


class StudentClassificationHead(nn.Module):
    """Trainable linear classification head on top of student encoder output.

    In the CDD notebook the teacher's frozen classifier serves this role.
    Since I-JEPA has no classifier we attach a fresh trainable head to the
    student encoder.

    Args:
        student_dim: Raw student encoder output dimension (e.g. 48).
        num_classes: Number of target classes.
    """

    def __init__(self, student_dim: int, num_classes: int) -> None:
        super().__init__()
        self.head = nn.Linear(student_dim, num_classes)

    def forward(self, student_emb: Tensor) -> Tensor:
        return self.head(student_emb)
