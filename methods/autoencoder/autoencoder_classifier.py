"""
Classificador que roda sobre o encoder do autoencoder pre-treinado.

Movido de src/models/models.py:533 (AutoEncoderClassifier). ``forward`` e o mesmo
byte a byte. Duas mudancas, ambas de import e nenhuma de numero:

1. O encoder vem de ``build`` (a unica fronteira de ``flim``) em vez de
   ``Encoder(arch, in_channels)``, e ``in_features`` sai de
   ``self.encoder.num_features`` (flim/encoder.py:89) — o mesmo valor que
   ``get_channels_from_arch(arch, in_channels)[-1]`` dava antes, sem precisar do
   parser de arch.
2. A ``MLPHead`` vem de ``core.blocks``. Nao ha copia local: a classe de
   core/blocks/mlp_head.py:30 e identica a src/models/models.py:304 — mesmas
   camadas na mesma ordem, mesmos defaults (hidden_dim=256, dropout=0.3) e os
   mesmos nomes de submodulo (``pool``, ``classifier``), logo as MESMAS chaves de
   state_dict (``head.classifier.0.weight`` e companhia).
"""

from typing import Optional

import torch
import torch.nn as nn

from core.blocks import MLPHead
from flim import build


class AutoEncoderClassifier(nn.Module):
    """
    Pretrained autoencoder encoder + MLP head.
    The decoder is discarded after pretraining.
    """

    def __init__(self, arch_json: str, init: str, num_classes: int,
                 weights_path: Optional[str] = None, in_channels: int = 3,
                 hidden_dim: int = 256, dropout: float = 0.3):
        super().__init__()
        self.encoder = build(arch_json, init, weights_path, in_channels)
        encoder_out_channels = self.encoder.num_features
        self.head = MLPHead(encoder_out_channels, num_classes, hidden_dim, dropout)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        features = self.encoder(x)
        return self.head(features)
