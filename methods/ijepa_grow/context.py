"""Tokens de contexto do aluno SPiFiL para o predictor I-JEPA."""

import torch
import torch.nn.functional as F
from torch import nn


class ContextTokenizer(nn.Module):
    """Mapa (B,C,H,W) -> conv 1x1 -> grid x grid -> tokens (B,grid*grid,ctx_dim) em ordem row-major."""

    def __init__(self, in_ch: int, ctx_dim: int = 384, grid: int = 16):
        super().__init__()
        self.proj = nn.Conv2d(in_ch, ctx_dim, kernel_size=1)
        self.grid = grid

    def forward(self, feat: torch.Tensor) -> torch.Tensor:
        x = F.adaptive_avg_pool2d(self.proj(feat), self.grid)
        return x.flatten(2).transpose(1, 2)


def gather_tokens(x: torch.Tensor, idx: torch.Tensor) -> torch.Tensor:
    """x (B,N,D), idx (B,K) -> (B,K,D)."""
    return torch.gather(x, 1, idx.unsqueeze(-1).expand(-1, -1, x.size(-1)))
