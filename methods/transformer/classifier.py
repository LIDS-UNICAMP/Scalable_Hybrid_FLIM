"""Classical head on the transformer's global vectors (the only fitted part)."""

from __future__ import annotations

import numpy as np
from sklearn.base import BaseEstimator
from sklearn.dummy import DummyClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import LinearSVC

__all__ = ["fit_classifier"]


def fit_classifier(
    x: np.ndarray, y: np.ndarray, kind: str, *, seed: int = 42
) -> BaseEstimator:
    """Standardise, then fit ``logreg`` or ``linear_svm`` on ``(x, y)``."""
    if len(np.unique(y)) < 2:
        # ponytail: constant predictor when train has a single class.
        return DummyClassifier(strategy="most_frequent").fit(x, y)
    clf = {
        "linear_svm": lambda: LinearSVC(
            class_weight="balanced", max_iter=10000, random_state=seed
        ),
        "logreg": lambda: LogisticRegression(
            max_iter=5000, class_weight="balanced", random_state=seed
        ),
    }
    if kind not in clf:
        raise ValueError(f"classificador desconhecido: {kind}")
    return Pipeline([("scale", StandardScaler()), ("clf", clf[kind]())]).fit(x, y)
