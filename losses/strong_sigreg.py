"""Strong-SIGReg do LeJEPA para o vetor z [B, C] depois do GeM. Sem rotulo, uma vista."""

import torch
from torch import Tensor

from core.losses.real_sigreg import RealSIGReg


class StrongSIGReg(RealSIGReg):
    """EP/N sobre z centrado e em escala global (RMS sem gradiente). K=16 para lote 32."""

    def __init__(self, n_proj: int = 16) -> None:
        super().__init__(n_proj=n_proj)

    def forward(self, z: Tensor) -> Tensor:
        zc = z.float() - z.float().mean(0)
        zc = zc / zc.detach().pow(2).mean().sqrt().clamp_min(1e-6)
        return super().forward(zc[None]) / z.size(0)


if __name__ == "__main__":
    torch.manual_seed(0)
    reg = StrongSIGReg()
    iso = torch.randn(32, 1280)
    cases = {
        "isotropico": iso,
        "posto1": torch.randn(32, 1) * torch.randn(1, 1280),
        "constante": torch.full((32, 1280), 2.73),
    }
    vals = {k: torch.stack([reg(v) for _ in range(200)]).mean().item() for k, v in cases.items()}
    print(vals)
    assert vals["posto1"] > vals["isotropico"] and vals["constante"] > vals["isotropico"]
    z = iso.clone().requires_grad_()
    reg(z).backward()
    assert z.grad.isfinite().all() and z.grad.abs().sum() > 0
    print("ok")
