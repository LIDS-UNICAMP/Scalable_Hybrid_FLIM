"""K2: ConvNeXt V2 Pico, 512-d. O unico Pico oficial no HF e o FCMAE ajustado com rotulo em ImageNet-1k."""
from transformers import ConvNextV2Model

from benchmark.common import extract

MODEL = "facebook/convnextv2-pico-1k-224"
REVISION = "90108c4fef94384bf77e904a4906f72ad6413c86"
PREPROCESS = "convnextv2_pico.fcmae_ft_in1k"


def load():
    net = ConvNextV2Model.from_pretrained(MODEL, revision=REVISION)
    return net, lambda x: net(x).pooler_output


if __name__ == "__main__":
    extract(MODEL, REVISION, PREPROCESS, load)
