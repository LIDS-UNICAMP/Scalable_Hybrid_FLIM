"""K5: AIMv2 3B, 3072-d (media dos tokens), entrada 448.

transformers 4.45.2 nao tem AIMv2, e o modeling_aimv2.py do repo apple/ nao casa com os nomes do
safetensors de la (carrega tudo aleatorio, sem erro). Pesos oficiais renomeados para o ViT do timm.
"""
import glob
import os

import timm
import torch
from huggingface_hub import snapshot_download
from safetensors.torch import load_file

from benchmark.common import extract

MODEL = "apple/aimv2-3B-patch14-448"
REVISION = "3501a9161cce2bbf5e46ad86abab4bc57ec6b1e5"
PREPROCESS = "aimv2_3b_patch14_448.apple_pt"
NAMES = {"rms_norm1": "norm1", "rms_norm2": "norm2", "attention.out_proj": "attn.proj",
         "ffn.gate_proj": "mlp.fc1_g", "ffn.up_proj": "mlp.fc1_x", "ffn.down_proj": "mlp.fc2"}


def _to_timm(sd):
    out = {"pos_embed": sd["embeddings.position_embedding.weight"][None],
           "patch_embed.proj.weight": sd["embeddings.patch_embed.weight"],
           "patch_embed.proj.bias": sd["embeddings.patch_embed.bias"],
           "patch_embed.norm.weight": sd["embeddings.rms_norm.weight"],
           "norm.weight": sd["rms_norm.weight"]}
    for i in range(24):
        old = f"encoder.layers.{i}."
        for a, b in NAMES.items():
            out[f"blocks.{i}.{b}.weight"] = sd[f"{old}{a}.weight"]
        out[f"blocks.{i}.attn.qkv.weight"] = torch.cat(
            [sd[f"{old}attention.{p}_proj.weight"] for p in "qkv"])
    return out


def load():
    folder = snapshot_download(MODEL, revision=REVISION, allow_patterns="model-*.safetensors")
    sd = {}
    for path in glob.glob(os.path.join(folder, "model-*.safetensors")):
        sd |= load_file(path)
    net = timm.create_model("aimv2_3b_patch14_448", pretrained=False, num_classes=0)
    net.load_state_dict(_to_timm(sd))
    return net, net


if __name__ == "__main__":
    extract(MODEL, REVISION, PREPROCESS, load)
