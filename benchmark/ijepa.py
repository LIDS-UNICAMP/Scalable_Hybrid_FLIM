"""K1: I-JEPA ViT-g/16 (ImageNet-22k), 1408-d. transformers 4.45.2 nao tem I-JEPA: safetensors no ViT do repo."""
from huggingface_hub import hf_hub_download

from benchmark.common import extract
from methods.lejepa.ijepa_encoder import _IJepaViT, _load_weights

MODEL = "facebook/ijepa_vitg16_22k"
REVISION = "2306205e956b753a39dae4fd38ec1c74145257d3"
PREPROCESS = "vit_giant_patch16_gap_224.in22k_ijepa"


def load():
    net = _IJepaViT(patch_size=16, hidden_size=1408, num_layers=40, mlp_ratio=48 / 11)
    _load_weights(net, hf_hub_download(MODEL, "model.safetensors", revision=REVISION))
    return net, net


if __name__ == "__main__":
    extract(MODEL, REVISION, PREPROCESS, load)
