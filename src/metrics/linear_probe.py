from __future__ import annotations

from typing import Optional

import torch
import torch.nn as nn
from torch import Tensor
from torchmetrics.functional import accuracy


class LinearProbeCallback:
    """
    Utility class to evaluate SSL representations with a linear probe.

    Usage in validation:
        1. Collect (features, labels) from the frozen encoder over the full val set.
        2. Fit a single linear layer with SGD for a few epochs.
        3. Report top-1 accuracy.

    This is intentionally kept lightweight — for full linear probe evaluation,
    use a dedicated fine-tuning run with `ClassificationFinetuneModule`.

    Args:
        embed_dim: Encoder output dimension.
        num_classes: Number of target classes.
        lr: Learning rate for the probe.
        epochs: Number of epochs for probe fitting.
    """

    def __init__(
        self,
        embed_dim: int,
        num_classes: int,
        lr: float = 0.01,
        epochs: int = 10,
    ) -> None:
        self.embed_dim = embed_dim
        self.num_classes = num_classes
        self.lr = lr
        self.epochs = epochs
        self.probe: Optional[nn.Linear] = None

    def fit(self, features: Tensor, labels: Tensor) -> None:
        """Fit the linear probe on the given features and labels."""
        device = features.device
        self.probe = nn.Linear(self.embed_dim, self.num_classes).to(device)
        optimizer = torch.optim.SGD(self.probe.parameters(), lr=self.lr, momentum=0.9)
        loss_fn = nn.CrossEntropyLoss()

        self.probe.train()
        for _ in range(self.epochs):
            optimizer.zero_grad()
            logits = self.probe(features)
            loss = loss_fn(logits, labels)
            loss.backward()
            optimizer.step()

    @torch.no_grad()
    def evaluate(self, features: Tensor, labels: Tensor) -> float:
        """Return top-1 accuracy of the fitted linear probe."""
        if self.probe is None:
            raise RuntimeError("Call .fit() before .evaluate()")
        self.probe.eval()
        logits = self.probe(features)
        acc = accuracy(logits, labels, task="multiclass", num_classes=self.num_classes)
        return float(acc)
