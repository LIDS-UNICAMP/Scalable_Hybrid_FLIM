from __future__ import annotations

import numpy as np
import torch
from torch import Tensor
from torchmetrics.functional.classification import (
    multiclass_accuracy,
    multiclass_cohen_kappa,
    multiclass_f1_score,
)


def compute_metrics(
    y_true: Tensor | np.ndarray,
    y_pred: Tensor | np.ndarray,
    num_classes: int,
    average: str = "macro",
) -> dict[str, float]:
    """Compute kappa, accuracy, and F1 for a single evaluation.

    Args:
        y_true: Ground truth class indices, shape (N,).
        y_pred: Predicted class indices (N,) or logits/probs (N, C).
        num_classes: Total number of classes.
        average: F1 averaging strategy — 'macro', 'micro', or 'weighted'.

    Returns:
        Dict with keys 'kappa', 'acc', 'f1'.
    """
    if isinstance(y_true, np.ndarray):
        y_true = torch.from_numpy(y_true)
    if isinstance(y_pred, np.ndarray):
        y_pred = torch.from_numpy(y_pred)

    y_true = y_true.long()
    if y_pred.ndim == 2:
        y_pred = y_pred.argmax(dim=1)
    y_pred = y_pred.long()

    return {
        "kappa": float(multiclass_cohen_kappa(y_pred, y_true, num_classes=num_classes)),
        "acc": float(multiclass_accuracy(y_pred, y_true, num_classes=num_classes)),
        "f1": float(multiclass_f1_score(y_pred, y_true, num_classes=num_classes, average=average)),
    }


def aggregate_metrics(
    scores: list[dict[str, float]],
    return_std: bool = False,
) -> dict[str, float]:
    """Aggregate metric dicts from multiple folds/runs into mean (± std).

    Args:
        scores: List of dicts from compute_metrics().
        return_std: If True, include '<key>_std' entries alongside the means.

    Returns:
        Dict with mean values and, optionally, std values.

    Example::
        fold_scores = [compute_metrics(y_true_k, y_pred_k, num_classes=5) for ...]
        results = aggregate_metrics(fold_scores, return_std=True)
        # {'kappa': 0.82, 'kappa_std': 0.03, 'acc': 0.91, ...}
    """
    keys = scores[0].keys()
    result: dict[str, float] = {}
    for k in keys:
        vals = np.array([s[k] for s in scores], dtype=np.float64)
        result[k] = float(vals.mean())
        if return_std:
            result[f"{k}_std"] = float(vals.std())
    return result
