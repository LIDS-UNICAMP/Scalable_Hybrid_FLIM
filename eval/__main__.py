"""Entry point for ``python -m eval``.

Origem: `src/evaluate/__main__.py`. Este e o UNICO `__main__.py` de modulo da
arvore nova — `eval/` o mantem de proposito (spec_refactor.md:2550).

Delegates to :func:`eval.unified_eval.main`, which accepts:

    python -m eval \\
        --mode  <svm|freeze|unfreeze|all> \\
        --init  <normal|trunc_norm|flim|he|xavier|random> \\
        [--resume] [--restart] [--resume_id <wandb_run_id>] \\
        [--dataset <eggs|protozoan|larvae|all>] \\
        [--split N] [--pct N] [--dry-run]

Mode mapping
------------
``--mode freeze``   → mlp_freeze evaluation
``--mode unfreeze`` → mlp_unfreeze evaluation
``--mode svm``      → SVM evaluation
``--mode all``      → SVM + mlp_unfreeze + mlp_freeze

Init filter
-----------
``--init trunc_norm`` → only trunc_normal_std SSL runs
``--init normal``     → all non-trunc_norm runs (xavier / he / random / flim)
``--init flim``       → only FLIM-initialised runs (backward compat)
(no --init)           → no filter — all initializers included

Resume / restart
----------------
``--resume``             → append to existing artifact CSVs; skip already-done
``--restart``            → regenerate current scope; replace matching rows
``--resume_id <run_id>`` → restrict to a specific W&B encoder run id

A origem chamava `main()` sem argumento nenhum e deixava o argparse de
`unified_eval` ler `sys.argv` por dentro. Com o argparse fora, quem traduz
`sys.argv` e `eval.svm.cli_kwargs`, aqui, uma vez.
"""
from eval.svm import cli_kwargs
from eval.unified_eval import main

if __name__ == "__main__":
    import sys

    main(**cli_kwargs(sys.argv[1:]))
